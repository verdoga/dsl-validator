package console

import "io"

// PrintHelp печатает dsl-validator [--depth N] <path>, правила глубины,
// обработки JSON на месте и коды завершения; возвращает ошибку вывода.
func PrintHelp(output io.Writer) error {
	_, err := io.WriteString(output, `Использование:
  dsl-validator [--depth N] <path>

Путь:
  Укажите один обычный файл .json (без учёта регистра) или каталог.
  Пустой аргумент "" означает текущий каталог; отсутствие пути — ошибка.
  Символические ссылки в пути не допускаются.

Параметры:
  --depth N  Предел уровней подкаталогов: целое число N не меньше нуля.
             Без --depth глубина не ограничена.
             При N=0 обрабатывается только исходный каталог.
             Для файла глубина игнорируется.
  --help, -h Показать справку.
  --         Завершить разбор флагов; далее передаётся путь.

  Флаги указываются до пути. Повторный --depth запрещён.
  Допустимы только указанные формы: -depth, --depth=N, -help и --h не поддерживаются.
  До пути и разделителя -- запрос справки имеет приоритет над ошибками аргументов.

Обработка:
  JSON обновляются по исходному пути; --replace не поддерживается.

Коды завершения:
  0 — штатное завершение или справка. Любое число диагностических срабатываний
      error (ошибки), warning (проблемы) и recommendation (рекомендации)
      не меняет код 0.
  1 — технический отказ: ошибка подготовки, обхода, обработки или вывода.
  2 — неверные аргументы или непригодный исходный путь.
`)
	return err
}
